#!/usr/bin/env node
/**
 * Refreshes the bundled public-holiday calendars used by the leave planner.
 *
 *   node scripts/build-holidays.mjs            # regenerate src/lib/generated/holidays.ts from src/data/holidays/*.json
 *   node scripts/build-holidays.mjs --download # fetch fresh data from Nager.Date first (no API key), then regenerate
 *
 * Only entries typed "Public" are kept. Regional entries keep their ISO 3166-2 region codes; dates the
 * provider marks "(Tentative Date)" (moon-sighting holidays in future years) keep a `tentative` flag.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const DATA_DIR = resolve(ROOT, 'src/data/holidays')
const OUTPUT = resolve(ROOT, 'src/lib/generated/holidays.ts')
const COUNTRIES = ['TR', 'DE', 'GB', 'US', 'FR', 'NL', 'BE', 'AT', 'RU', 'KZ']
const FIRST_YEAR = 2025
const LAST_YEAR = 2029
const API = (year, country) => `https://date.nager.at/api/v3/PublicHolidays/${year}/${country}`
const TENTATIVE = /\s*\((tentative date|tentative)\)\s*/i

async function download(url) {
  const response = await fetch(url, { headers: { 'User-Agent': 'tools.mucahid.dev data refresh', Accept: 'application/json' } })
  if (!response.ok) throw new Error(`${url} responded ${response.status}`)
  return response.json()
}

/** Keeps public holidays only, strips the tentative marker into a flag and drops exact duplicates. */
function normalise(list) {
  const seen = new Set()
  const entries = []
  for (const holiday of list) {
    if (!Array.isArray(holiday.types) || !holiday.types.includes('Public')) continue
    const tentative = TENTATIVE.test(holiday.localName ?? '') || TENTATIVE.test(holiday.name ?? '')
    const local = String(holiday.localName ?? holiday.name).replace(TENTATIVE, '').trim()
    const name = String(holiday.name ?? holiday.localName).replace(TENTATIVE, '').trim()
    const counties = holiday.global ? undefined : Array.isArray(holiday.counties) ? [...holiday.counties].sort() : undefined
    const key = `${holiday.date}|${local}|${(counties ?? []).join(',')}`
    if (seen.has(key)) continue
    seen.add(key)
    entries.push({ date: holiday.date, local, name, ...(counties ? { counties } : {}), ...(tentative ? { tentative: true } : {}) })
  }
  return entries.sort((a, b) => a.date.localeCompare(b.date) || a.local.localeCompare(b.local))
}

async function main() {
  const shouldDownload = process.argv.includes('--download')
  mkdirSync(DATA_DIR, { recursive: true })
  if (shouldDownload) {
    for (const country of COUNTRIES) {
      const years = {}
      for (let year = FIRST_YEAR; year <= LAST_YEAR; year += 1) {
        process.stdout.write(`Downloading ${country} ${year} … `)
        years[year] = normalise(await download(API(year, country)))
        console.log(`${years[year].length} holidays`)
      }
      writeFileSync(resolve(DATA_DIR, `${country}.json`), `${JSON.stringify({ country, source: 'Nager.Date (https://date.nager.at), MIT licence', fetchedAt: new Date().toISOString().slice(0, 10), years }, null, 1)}\n`)
    }
  }
  const generatedAt = new Date().toISOString().slice(0, 10)
  const data = Object.fromEntries(COUNTRIES.map((country) => [country, JSON.parse(readFileSync(resolve(DATA_DIR, `${country}.json`), 'utf8')).years]))
  const years = Array.from({ length: LAST_YEAR - FIRST_YEAR + 1 }, (_, index) => FIRST_YEAR + index)
  const output = [
    `/* Generated by scripts/build-holidays.mjs on ${generatedAt}. Do not edit by hand; see src/data/SOURCES.md. */`,
    `export type HolidayCountry = ${COUNTRIES.map((country) => `'${country}'`).join(' | ')}`,
    `export const HOLIDAY_COUNTRIES: readonly HolidayCountry[] = [${COUNTRIES.map((country) => `'${country}'`).join(', ')}]`,
    `export const HOLIDAY_YEARS: readonly number[] = [${years.join(', ')}]`,
    `export const HOLIDAYS_GENERATED_AT = '${generatedAt}'`,
    `/** \`counties\` lists the ISO 3166-2 regions a holiday applies to (nationwide holidays omit it); \`tentative\` marks dates the provider has not confirmed. */`,
    `export type HolidayEntry = { date: string; local: string; name: string; counties?: string[]; tentative?: boolean }`,
    `export const HOLIDAYS: Record<HolidayCountry, Record<number, HolidayEntry[]>> = ${JSON.stringify(data)}`,
    '',
  ].join('\n')
  mkdirSync(dirname(OUTPUT), { recursive: true })
  writeFileSync(OUTPUT, output)
  console.log(`Wrote ${OUTPUT} (${output.length} bytes)`)
}

main().catch((error) => { console.error(error); process.exit(1) })
