import { expect, test } from '@playwright/test'

test.describe('tool history', () => {
  test('saves, restores, deletes and never resurrects deleted queries', async ({ page }) => {
    await page.goto('/tools/loan-calculator')
    const amount = page.getByLabel('Kredi tutarı')
    await amount.fill('250000')
    await page.waitForTimeout(1500)
    await amount.fill('300000')
    await page.waitForTimeout(1500)
    const toggle = page.getByRole('button', { name: /Son sorgular/ })
    await expect(toggle).toContainText('2/10')
    await toggle.click()
    const items = page.locator('.history-item')
    await expect(items).toHaveCount(2)
    await expect(items.first()).toContainText('300000')
    await items.first().getByRole('button', { name: 'Kaydı sil' }).click()
    await expect(items).toHaveCount(1)
    await amount.fill('400000')
    await page.waitForTimeout(1500)
    await expect(items).toHaveCount(2)
    await expect(page.locator('.history-item', { hasText: '300000' })).toHaveCount(0)
    await page.locator('.history-item', { hasText: '250000' }).getByRole('button', { name: 'Bu sorguyu geri yükle' }).click()
    await expect(amount).toHaveValue('250000')
    await page.reload()
    await expect(page.getByRole('button', { name: /Son sorgular/ })).toContainText('2/10')
    await page.getByRole('button', { name: /Son sorgular/ }).click()
    await page.getByRole('button', { name: 'Tümünü sil' }).click()
    await expect(page.getByRole('button', { name: /Son sorgular/ })).toContainText('0/10')
  })

  test('history is separate per tool and includes the conversion rate field', async ({ page }) => {
    await page.goto('/tools/loan-calculator')
    await page.getByLabel('Dönüşüm oranı').fill('0.03')
    await page.waitForTimeout(1500)
    const stored = await page.evaluate(() => localStorage.getItem('tools:history:v2:loan-calculator') ?? '')
    expect(stored).toContain('"conversion":"0.03"')
    expect(stored).not.toContain('Dönüşüm')
    await page.getByLabel('Dönüşüm oranı').fill('0.05')
    await page.waitForTimeout(1500)
    await page.getByRole('button', { name: /Son sorgular/ }).click()
    await page.locator('.history-item').nth(1).getByRole('button', { name: 'Bu sorguyu geri yükle' }).click()
    await expect(page.getByLabel('Dönüşüm oranı')).toHaveValue('0.03')
    await page.goto('/tools/vat-calculator')
    await expect(page.getByRole('button', { name: /Son sorgular/ })).toContainText('0/10')
  })
})

