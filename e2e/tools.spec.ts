test.describe('growth calculators', () => {
  test('compound, savings and investment pages share one form with different presets', async ({ page }) => {
    await page.goto('/tools/compound-interest-calculator')
    await expect(page.getByRole('button', { name: 'Bileşik Faiz', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(page.getByLabel('Düzenli katkı')).toHaveCount(0)
    await expect(page.getByText(/sonra toplam değer/)).toBeVisible()
    await page.goto('/tools/savings-calculator')
    await expect(page.getByRole('button', { name: 'Tasarruf', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(page.getByLabel('Düzenli katkı')).toBeVisible()
    await page.goto('/tools/investment-calculator')
    await expect(page.getByRole('button', { name: 'Yatırım', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(page.getByRole('combobox', { name: 'Bileşik sıklığı' })).toBeVisible()
    await page.getByRole('button', { name: 'Tasarruf', exact: true }).click()
    await expect(page).toHaveURL(/savings-calculator/)
    await page.getByRole('switch', { name: /Gerçek geçmiş verilerle hesapla/ }).click()
    await expect(page.getByRole('combobox', { name: 'Varlık' })).toBeVisible()
    await expect(page).toHaveURL(/historical-investment-calculator/)
  })

  test('historical mode can contribute in another currency', async ({ page }) => {
    await page.goto('/tools/historical-investment-calculator')
    await expect(page.getByRole('combobox', { name: 'Varlık' })).toBeVisible()
    await page.getByRole('switch', { name: 'Gelişmiş para birimi seçenekleri' }).click()
    await page.getByRole('combobox', { name: 'Katkı para birimi' }).click()
    await page.getByRole('option', { name: /US dollar|Amerikan doları/ }).click()
    await page.getByLabel('Düzenli katkı').fill('100')
    await expect(page.getByText(/USD → TRY/)).toBeVisible()
    await expect(page.getByText(/her ay \$100/)).toBeVisible()
  })

  test('the inflation toggle adds real values for projections and history', async ({ page }) => {
    await page.goto('/tools/investment-calculator')
    await expect(page.getByText('Enflasyon kaybı')).toHaveCount(0)
    await page.getByRole('switch', { name: /Enflasyonu hesaba kat/ }).click()
    await expect(page.getByRole('combobox', { name: 'Enflasyon verisi ülkesi' })).toHaveText(/Türkiye/)
    const rate = page.getByLabel('Tahmini enflasyon (TRY)')
    await expect(rate).not.toHaveValue('')
    await expect(page.getByText('Enflasyon kaybı').first()).toBeVisible()
    await expect(page.getByText('Reel yıllık getiri')).toBeVisible()
    await rate.fill('0')
    await expect(page.getByText(/yatırım enflasyonu yeniyor/)).toBeVisible()
    await page.getByRole('combobox', { name: 'Enflasyon verisi ülkesi' }).click()
    await page.getByRole('option', { name: /ABD/ }).click()
    await expect(rate).not.toHaveValue('0')
    await page.getByRole('switch', { name: /Gerçek geçmiş verilerle hesapla/ }).click()
    await expect(page.getByText('Reel kâr / zarar')).toBeVisible()
    await expect(page.getByLabel('Tahmini enflasyon (TRY)')).toHaveCount(0)
    await page.getByRole('switch', { name: /Enflasyonu hesaba kat/ }).click()
    await expect(page.getByText('Reel kâr / zarar')).toHaveCount(0)
  })

  test('result tables switch between yearly totals and one year of months', async ({ page }) => {
    await page.goto('/tools/savings-calculator')
    await expect(page.getByRole('tab', { name: 'Yıllık' })).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByRole('cell', { name: 'Toplam', exact: true })).toBeVisible()
    await page.getByRole('tab', { name: 'Aylık' }).click()
    await expect(page.getByRole('button', { name: '5. yıl', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(page.getByRole('cell', { name: '5. yıl toplamı' })).toBeVisible()
    await page.getByRole('button', { name: '2. yıl', exact: true }).click()
    await expect(page.getByRole('cell', { name: '13. ay', exact: true })).toBeVisible()
    await page.getByRole('combobox', { name: 'Yıl seç' }).click()
    await page.getByRole('option', { name: '4. yıl' }).click()
    await expect(page.getByRole('cell', { name: '4. yıl toplamı' })).toBeVisible()
    await page.getByRole('switch', { name: /Gerçek geçmiş verilerle hesapla/ }).click()
    await expect(page.getByRole('tab', { name: 'Aylık' })).toHaveAttribute('aria-selected', 'true')
    await page.getByRole('button', { name: 'Önceki yıl' }).click()
    await expect(page.getByRole('cell', { name: /^2025 toplamı$/ })).toBeVisible()
  })

  test('projections can contribute in another currency along an inflation-based rate path', async ({ page }) => {
    await page.goto('/tools/investment-calculator')
    await page.getByRole('switch', { name: 'Gelişmiş para birimi seçenekleri' }).click()
    await page.getByRole('combobox', { name: 'Katkı para birimi' }).click()
    await page.getByRole('option', { name: /Amerikan doları/ }).click()
    const rate = page.getByLabel('Bugünkü kur')
    const rateValue = Number(await rate.inputValue())
    expect(rateValue).toBeGreaterThan(30)
    const lira = page.getByLabel('Tahmini enflasyon (TRY)')
    const dollar = page.getByLabel('Tahmini enflasyon (USD)')
    expect(Number(await lira.inputValue())).toBeGreaterThan(15)
    expect(Number(await dollar.inputValue())).toBeGreaterThan(1)
    await expect(page.getByText(/Kur tahmini/)).toBeVisible()
    await expect(page.getByText(/\$60\.000/).first()).toBeVisible()
    await page.getByRole('tab', { name: 'Aylık' }).click()
    await expect(page.getByRole('columnheader', { name: 'Kur' })).toBeVisible()
    await expect(page.getByRole('columnheader', { name: 'Katkı (USD)' })).toBeVisible()
    await page.getByRole('group', { name: 'Oran birimi' }).getByRole('button', { name: 'Aylık' }).click()
    const monthly = Number(await lira.inputValue())
    expect(monthly).toBeGreaterThan(0.5)
    expect(monthly).toBeLessThan(5)
    await lira.fill('3')
    await expect(page.getByText(/↺ 10 yıl ort\./)).toBeVisible()
    await page.getByRole('switch', { name: /Enflasyonu hesaba kat/ }).click()
    await expect(page.getByText('Enflasyon kaybı').first()).toBeVisible()
  })
})

